"""The declared baseline: each person's groups, generated from their manifest.

A re-implementation of goat's `ops/warrant/membership.py --generate-baseline`
(design mesh-change-control.md §4.2). Where the two could differ, goat's is
right.

For every operator manifest (`ops/operators/<env>/<handle>.yml` in goat; here
`fixtures/manifests/<env>/<handle>.yml`) that is `identity.status: active`, has
`netbird.enabled` not false, and lists the scope in `netbird.sites`:

    device   = netbird.auto_groups, each as <site_prefix>-<suffix>
               (retired tokens translated: VENDOR -> DEVELOPER, ADMIN -> PLATFORM-ADMIN)
    handset  = <P>-OBSERVER, plus <P>-HANDSET where the taxonomy declares it:
               the set for the person's phones and tablets, whose key is
               OBSERVER-only whatever auto_groups says. Left out entirely when
               netbird.handset_limit is 0 (no phone-and-tablet key is minted)

The output is deterministic — sorted, no timestamps — so CI can say "stale"
with a plain byte compare.
"""

from __future__ import annotations

from pathlib import Path

import yaml

LEGACY_SUFFIX = {"VENDOR": "DEVELOPER", "ADMIN": "PLATFORM-ADMIN"}


class BaselineError(Exception):
    pass


def load_manifests(root: Path) -> list[tuple[Path, dict]]:
    out = []
    for f in sorted(Path(root).glob("*/*.yml")):
        doc = yaml.safe_load(f.read_text())
        if isinstance(doc, dict) and isinstance(doc.get("identity"), dict):
            out.append((f, doc))
    return out


def generate(scope: str, taxonomy: dict, manifests: list[tuple[Path, dict]]) -> dict:
    prefix = taxonomy[scope]["site_prefix"]
    suffixes = set(taxonomy[scope]["suffixes"])
    people: dict[str, dict[str, list[str]]] = {}
    problems: list[str] = []
    for f, doc in manifests:
        ident, nb = doc.get("identity") or {}, doc.get("netbird") or {}
        if ident.get("status") != "active" or nb.get("enabled") is False:
            continue
        if scope not in [str(s) for s in nb.get("sites") or []]:
            continue
        handle = str(ident.get("handle") or "")
        if handle in people:
            problems.append(f"{f.name}: handle {handle!r} is claimed twice")
            continue
        device = set()
        for tok in nb.get("auto_groups") or []:
            sfx = LEGACY_SUFFIX.get(str(tok), str(tok))
            if sfx not in suffixes:
                problems.append(f"{f.name}: auto_groups token {tok!r} is not a {scope} group")
                continue
            device.add(f"{prefix}-{sfx}")
        people[handle] = {"device": sorted(device)}
        if nb.get("handset_limit") != 0:
            people[handle]["handset"] = sorted(
                [f"{prefix}-OBSERVER"] + ([f"{prefix}-HANDSET"] if "HANDSET" in suffixes else []))
    if problems:
        raise BaselineError("; ".join(problems))
    return {"version": 1, "scope": scope,
            "generated_from": f"fixtures/manifests/<env>/*.yml: active manifests whose netbird.sites includes {scope}",
            "people": dict(sorted(people.items()))}


def render(doc: dict) -> str:
    lines = [
        "# GENERATED by `bin/mcc baseline --write` from the made-up manifests in",
        "# fixtures/manifests/ (in goat: ops/warrant/membership.py --generate-baseline",
        "# from ops/operators/). Do not edit; change a manifest and regenerate.",
        "version: 1",
        f"scope: {doc['scope']}",
        f'generated_from: "{doc["generated_from"]}"',
    ]
    if not doc["people"]:
        lines.append("people: {}")
    else:
        lines.append("people:")
        for h, sets in doc["people"].items():
            lines += [f"  {h}:", f"    device: [{', '.join(sets['device'])}]"]
            if "handset" in sets:
                lines.append(f"    handset: [{', '.join(sets['handset'])}]")
    return "\n".join(lines) + "\n"
